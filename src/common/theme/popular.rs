/// All popular themes, in table order.
pub(super) fn themes() -> Vec<ThemeInfo> {
    PALETTES.iter().map(to_theme).collect()
}

/// Maps the source colours onto the tokens. Dark and light themes are mapped separately, so the
/// text stays readable on the background in both: the page is the background (lighter or darker
/// shade), the card the raised shade, and the accent-ink is the background colour.
fn to_theme(p: &Palette) -> ThemeInfo {
    let colors = if p.dark {
        [
            p.bg,
            p.bg_light,
            p.bg,
            p.selection,
            p.fg,
            p.fg_dim,
            p.accent,
            p.bg,
            p.red,
        ]
    } else {
        [
            p.bg_dark,
            p.bg,
            p.bg,
            p.selection,
            p.fg,
            p.fg_dim,
            p.accent,
            p.bg,
            p.red,
        ]
    };
    theme(p.id, p.name, p.dark, colors)
}
